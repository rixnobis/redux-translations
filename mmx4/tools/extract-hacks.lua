-- Pull what the archive needs out of the 2004 French patcher (mmx4-hack.lua).
-- Run with luajit: extract-hacks.lua mmx4-hack.lua slus-hacks.lua [mmx4-index.lua]
-- slus-hacks.lua gets the executable patches, which are translation content and
-- only ship in the zip. mmx4-index.lua gets the file table's names and which
-- entry the patch processes how, which is structure and lives in the repository.
local src = assert(io.open(arg[1], 'rb')):read('*a')
local env = {}
setfenv(assert(loadstring(src, '@' .. arg[1])), env)()

local function sortedKeys(t)
    local keys = {}
    for k in pairs(t) do keys[#keys + 1] = k end
    table.sort(keys)
    return keys
end

-- Only the USA executable: the patcher's Japanese path stops with an error.
local keys = sortedKeys(env.slus_hacks)
local out = assert(io.open(arg[2], 'w'))
out:write('-- Executable offset -> replacement bytes.\nreturn {\n')
for _, k in ipairs(keys) do
    local b = {}
    for i, v in ipairs(env.slus_hacks[k]) do b[i] = string.format('\\%d', v) end
    out:write(string.format('    [0x%05x] = "%s",\n', k, table.concat(b)))
end
out:write('}\n')
out:close()
print(#keys .. ' patches')
if not arg[3] then return end

local names, arcs, subs, intro = {}, {}, {}, {}
for i, n in ipairs(env.filenames) do names[i] = string.format("        [%d] = '%s',", i - 1, n) end
for _, i in ipairs(sortedKeys(env.mmx4_index)) do
    local e = env.mmx4_index[i]
    if type(e) == 'table' then
        if e.func == env.arc_patch then
            local parts = {}
            for _, k in ipairs(sortedKeys(e.args)) do parts[#parts + 1] = string.format("[%d] = '%s'", k, e.args[k]) end
            arcs[#arcs + 1] = string.format('        [%d] = { %s }, -- %s', i, table.concat(parts, ', '), env.filenames[i + 1])
        elseif e.func == env.str_process then
            subs[i] = e.args.name
        elseif e.func == env.create_intro then
            intro[#intro + 1] = string.format('        [%d] = true, -- %s', i, env.filenames[i + 1])
        else
            error('entry ' .. i .. ': unknown processing')
        end
    end
end
-- Every movie has Japanese-soundtrack subtitles; OP_U.STR has no others.
local movies = {}
for _, i in ipairs(sortedKeys(env.videos_jap_override)) do
    local jap = env.videos_jap_override[i].args
    movies[#movies + 1] = string.format("        [%d] = { %sjap = '%s', xa = '%s' }, -- %s", i,
        subs[i] and string.format("subs = '%s', ", subs[i]) or '', jap.name, jap.xa_name, env.filenames[i + 1])
end

out = assert(io.open(arg[3], 'w'))
out:write([[
-- Mega Man X4 (USA): the executable's file table, and what the 2004 French
-- patch does to each entry. Generated by tools/extract-hacks.lua from the
-- patcher's filenames, mmx4_index and videos_jap_override.
return {
    -- Entries 0..159 of the table, in order. 160..162 are SYSTEM.CNF, the
    -- executable and ZNULL.DAT, which the game does not load through it.
    names = {
]] .. table.concat(names, '\n') .. [[

    },
    -- ARC files whose subfiles (counted from 0) are replaced by pack files.
    arcs = {
]] .. table.concat(arcs, '\n') .. [[

    },
    -- Movies: the pack folder of subtitles for the English soundtrack (subs),
    -- the one for the Japanese soundtrack (jap), and the Japanese audio (xa,
    -- MEDIA/<xa>.xa in the pack).
    movies = {
]] .. table.concat(movies, '\n') .. [[

    },
    -- The movie the patch replaces with a credits intro built from INTRO/.
    intro = {
]] .. table.concat(intro, '\n') .. [[

    },
}
]])
out:close()
print(#names .. ' names, ' .. #arcs .. ' arcs, ' .. #movies .. ' movies, ' .. #intro .. ' intro')
